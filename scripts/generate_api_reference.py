"""Generate the bound API type reference without importing the native module.

Run from any directory; --check reports stale output without changing files.
Only the nanobind declaration patterns used by this repository are supported.
Unresolved direct members fail generation rather than producing guessed defaults.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/api/types.md"
BINDINGS = ROOT / "photara/src/python/bindings.cpp"


def cell(value: str) -> str:
    return " ".join(value.split()).replace("|", "\\|")


def struct_body(text: str, start: int) -> str:
    # Ignore comments and strings while balancing initializer/nested-type braces.
    tokens = re.finditer(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|[{}]', text[start:])
    depth = 0
    for token in tokens:
        if token.group() == "{":
            depth += 1
        elif token.group() == "}":
            depth -= 1
            if depth == 0:
                return text[start:start + token.end()]
    raise ValueError("Unbalanced C++ struct")


def generate() -> str:
    source = BINDINGS.read_text(encoding="utf-8")
    structs = {}
    for header in sorted((ROOT / "photara/include").rglob("*.hpp")):
        text = header.read_text(encoding="utf-8")
        namespace = re.search(r"namespace\s+(photara(?:::\w+)*)\s*\{", text)
        if not namespace:
            continue
        for match in re.finditer(r"\bstruct\s+(\w+)\s*\{", text):
            name = namespace[1] + "::" + match[1]
            structs[name] = (header, text, match.start(), struct_body(text, match.end() - 1))

    out = ["# API types and enumerations", "",
           "Generated by `python scripts/generate_api_reference.py`; do not edit the tables by hand.", "",
           "See [Python API](python.md) and [C++ API](cpp.md) for call contracts and examples.", "",
           "Python names are prefixed with `photara.`. C++ abbreviations `sfm`, `mvs`, `splat`,",
           "and `ba` below mean `photara::sfm`, `photara::mvs`, `photara::splat`, and `photara::ba`.",
           "Types and initializers are C++ declarations, not Python assignment syntax.",
           "`{}` denotes value initialization; an empty path is not an automatically created directory.",
           "Initializers describe a new default object; presets and pipeline calls may change it.",
           "Read-only result initializers are not successful-run values. Source comments are reproduced",
           "where present; follow the declaration link for additional surrounding context.", "",
           "This lists the Python-exposed subset of C++ members. C++ may expose additional fields.", "",
           "## Enumerations", "",
           "| Python enum | C++ enum | Python member → C++ member |", "|---|---|---|"]
    enum_pattern = r'nb::enum_<([^>]+)>\(\s*module,\s*"([^"]+)"\)([\s\S]*?);'
    for enum in re.finditer(enum_pattern, source):
        values = re.findall(r'\.value\(\s*"([^"]+)",\s*([\w:]+)\s*\)', enum[3])
        if not values:
            raise ValueError(f"No enum values parsed: {enum[2]}")
        out.append(f"| `{enum[2]}` | `{enum[1]}` | " + "; ".join(f"`{a}` → `{b.split('::')[-1]}`" for a, b in values) + " |")

    classes = list(re.finditer(r'nb::class_<([^>]+)>\(\s*module,\s*"([^"]+)"\)', source))
    out += ["", "## Type index", ""]
    out += [f"- [{m[2]}](#{m[2].lower()}) — `{m[1]}`" for m in classes]
    for index, match in enumerate(classes):
        cpp, name = match[1], match[2]
        end = classes[index + 1].start() if index + 1 < len(classes) else len(source)
        block = source[match.end():end]
        out += ["", f"## {name}", "", f"C++: `{cpp}`. " +
                ("Construct with `photara." + name + "()`." if ".def(nb::init<>())" in block else "Returned by API calls; no Python constructor is bound."), ""]
        members = [(m[2], m[1], m[3], m[4]) for m in re.finditer(
            r'\.def_(rw|ro)\(\s*"([^"]+)",\s*&([\w:]+)::(\w+)\s*\)', block)]
        members += [(m[2], "rw", m[1], m[2]) for m in re.finditer(
            r'PHOTARA_BIND_RW\(\w+,\s*([\w:]+),\s*(\w+)\)', block)]
        if members:
            out += ["| Python field | Access | C++ type | Initializer | Description / declaration |", "|---|---|---|---|---|"]
        for field, access, owner, native in members:
            qualified = owner if owner.startswith("photara::") else "photara::" + owner
            if qualified not in structs:
                # Handle wrapper-owned fields are documented in the Python guide.
                if owner.endswith("Handle"):
                    out.append(f"| `{field}` | read-only | wrapper field | — | See [result handles](python.md#result-handles). |")
                    continue
                raise ValueError(f"Cannot resolve type {owner}")
            header, text, offset, body = structs[qualified]
            decl = re.search(r'^[ \t]+([\w:<>, \t]+?)[ \t]+' + re.escape(native) +
                             r'[ \t]*(\{[^;]*?\}|=[^;]*|)[ \t]*;', body, re.MULTILINE)
            if not decl:
                raise ValueError(f"Cannot resolve member {owner}::{native}")
            # Collect immediately preceding and trailing line comments.
            before = body[:decl.start()].splitlines()
            comments = []
            for line in reversed(before):
                if line.strip().startswith("//"):
                    comments.insert(0, line.strip()[2:].strip())
                else:
                    break
            tail = body[decl.end():].splitlines()[0]
            if tail.strip().startswith("//"):
                comments.append(tail.strip()[2:].strip())
            line = text[:offset].count("\n") + body[:decl.start()].count("\n") + 1
            # Account for the struct declaration preceding its opening brace.
            line += text[offset:text.index("{", offset)].count("\n")
            link = f"[source](../../{header.relative_to(ROOT).as_posix()}#L{line})"
            initializer = cell(decl[2]) or "default initialization"
            out.append(f"| `{field}` | {'read/write' if access == 'rw' else 'read-only'} | `{cell(decl[1])}` | `{initializer}` | {cell(' '.join(comments))} {link} |")
        properties = re.findall(r'\.def_prop_ro\(\s*"([^"]+)"', block)
        methods = re.findall(r'(?<!\w)\.def\(\s*"([^"]+)"', block)
        if properties:
            out += ["", "Read-only properties: " + ", ".join(f"`{p}`" for p in properties) + ". See [result handles](python.md#result-handles)."]
        if methods:
            out += ["", "Methods: " + ", ".join(f"`{p}()`" for p in methods) + ". See [Python API](python.md) for signatures and behavior."]
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        guide = (ROOT / "docs/api/python.md").read_text(encoding="utf-8")
        functions = re.findall(r'module\.def\(\s*"([^"]+)"', BINDINGS.read_text(encoding="utf-8"))
        missing = [name for name in functions if not re.search(r'\b' + name + r'\(', guide)]
        if missing:
            raise SystemExit("Python function guide is missing: " + ", ".join(missing))
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("API reference is stale: run python scripts/generate_api_reference.py")
        print("API type reference is current.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
